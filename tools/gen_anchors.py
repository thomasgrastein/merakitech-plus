#!/usr/bin/env python3
"""gen_anchors.py — the pinned TLS trust anchors of the on-device updater (docs/ota-plan.md §6.2, phase 3).

    python3 tools/gen_anchors.py --floor 2026-11-26      write src/merakiplus_upd_anchors.h from keys/tls/*.crt
    python3 tools/gen_anchors.py --check                 exit 1 when the header differs from keys/tls/ (hygiene, CI)

keys/tls/*.crt are self-signed root certificates (PEM). BearSSL needs only each root's subject DN (raw DER) and public
key, so the header holds exactly that (the same data `brssl ta` emits) and nothing is parsed at run time. --floor is
the clock floor: certificates are checked against max(device clock, floor), so a device whose clock reset still
validates (until GitHub's certificates are renewed after that date). Refresh it together with the anchors.
Standard library only; the output is deterministic (sorted by file name).
"""
import argparse
import base64
import datetime
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "keys" / "tls"
OUT = ROOT / "src" / "merakiplus_upd_anchors.h"
CURVES = {"2a8648ce3d030107": ("BR_EC_secp256r1", 65), "2b81040022": ("BR_EC_secp384r1", 97),
          "2b81040023": ("BR_EC_secp521r1", 133)}
OID_RSA, OID_EC = "2a864886f70d010101", "2a8648ce3d0201"


def tlv(d, i):
    """(tag, header length, content length) of the DER element at i."""
    tag, n = d[i], d[i + 1]
    if n < 0x80:
        return tag, 2, n
    k = n & 0x7F
    if not 1 <= k <= 3:
        raise ValueError("bad DER length")
    return tag, 2 + k, int.from_bytes(d[i + 2:i + 2 + k], "big")


def children(d, i):
    tag, h, n = tlv(d, i)
    j, out = i + h, []
    while j < i + h + n:
        out.append(j)
        t, hh, nn = tlv(d, j)
        j += hh + nn
    return out


def elem(d, i):
    _, h, n = tlv(d, i)
    return d[i:i + h + n]


def content(d, i):
    _, h, n = tlv(d, i)
    return d[i + h:i + h + n]


def parse(der):
    """subject DN (raw), issuer DN (raw), key ('rsa', n, e) | ('ec', curve, point), subject text"""
    tbs = children(der, 0)[0]
    f = children(der, tbs)
    if der[f[0]] == 0xA0:                      # [0] version
        f = f[1:]
    issuer, subject, spki = f[2], f[4], f[5]
    alg, key = children(der, spki)
    algf = children(der, alg)
    oid = content(der, algf[0]).hex()
    bits = content(der, key)
    if bits[0] != 0:
        raise ValueError("unused bits in the public key")
    bits = bits[1:]
    if oid == OID_RSA:
        n_i, e_i = children(bits, 0)
        n, e = content(bits, n_i).lstrip(b"\0"), content(bits, e_i).lstrip(b"\0")
        k = ("rsa", n, e)
    elif oid == OID_EC:
        cv = content(der, algf[1]).hex()
        if cv not in CURVES or len(bits) != CURVES[cv][1] or bits[0] != 4:
            raise ValueError(f"unsupported EC key (curve {cv})")
        k = ("ec", CURVES[cv][0], bits)
    else:
        raise ValueError(f"unsupported key algorithm {oid}")
    cn = "?"
    for rdn in children(der, subject):                       # SET { SEQUENCE { OID, value } }
        for atv in children(der, rdn):
            o, v = children(der, atv)
            if content(der, o) == b"\x55\x04\x03":
                cn = content(der, v).decode("latin-1")
    return elem(der, subject), elem(der, issuer), k, cn


def carr(name, b):
    rows = [", ".join(f"0x{x:02X}" for x in b[i:i + 16]) for i in range(0, len(b), 16)]
    return f"static const unsigned char {name}[] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def render(floor):
    certs = sorted(SRC.glob("*.crt"))
    if not certs:
        sys.exit(f"gen_anchors.py: no *.crt in {SRC}")
    out = ["/* merakiplus_upd_anchors.h — GENERATED by tools/gen_anchors.py from the root certificates in keys/tls/. Do not edit.\n"
           " * The pinned TLS roots of the on-device updater (docs/ota-plan.md §6.2; rotation: keys/tls/README.md).\n"
           " * Each anchor is a root's subject DN + public key, as BearSSL's br_x509_trust_anchor needs them. */\n",
           f"#define MP_CLOCK_FLOOR {int(floor.timestamp())}LL      /* {floor.date().isoformat()} 00:00 UTC: certificates are"
           " checked at max(clock, this) */\n"]
    tas = []
    for k, p in enumerate(certs):
        m = re.search(rb"-----BEGIN CERTIFICATE-----(.*?)-----END CERTIFICATE-----", p.read_bytes(), re.S)
        if not m:
            sys.exit(f"gen_anchors.py: {p.name} is not a PEM certificate")
        der = base64.b64decode(b"".join(m.group(1).split()))
        dn, issuer, key, cn = parse(der)
        if dn != issuer:
            sys.exit(f"gen_anchors.py: {p.name} is not self-signed (pin roots only)")
        out.append(f"\n/* {p.name}: {cn} */\n")
        out.append(carr(f"TA{k}_DN", dn))
        if key[0] == "rsa":
            out.append(carr(f"TA{k}_RSA_N", key[1]) + carr(f"TA{k}_RSA_E", key[2]))
            pk = (f"{{ BR_KEYTYPE_RSA, {{ .rsa = {{ (unsigned char *)TA{k}_RSA_N, sizeof TA{k}_RSA_N, "
                  f"(unsigned char *)TA{k}_RSA_E, sizeof TA{k}_RSA_E }} }} }}")
        else:
            out.append(carr(f"TA{k}_EC_Q", key[2]))
            pk = f"{{ BR_KEYTYPE_EC, {{ .ec = {{ {key[1]}, (unsigned char *)TA{k}_EC_Q, sizeof TA{k}_EC_Q }} }} }}"
        tas.append(f"    {{ {{ (unsigned char *)TA{k}_DN, sizeof TA{k}_DN }}, BR_X509_TA_CA, {pk} }},   /* {cn} */\n")
    out.append("\nstatic const br_x509_trust_anchor MP_ANCHORS[] = {\n" + "".join(tas) + "};\n")
    out.append(f"#define MP_ANCHORS_NUM {len(tas)}\n")
    return "".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--floor", help="clock floor YYYY-MM-DD (default: the one in the current header)")
    ap.add_argument("--check", action="store_true", help="compare instead of writing")
    a = ap.parse_args()
    floor = a.floor
    if not floor:
        m = re.search(r"/\* (\d{4}-\d{2}-\d{2}) 00:00 UTC", OUT.read_text()) if OUT.is_file() else None
        if not m:
            sys.exit("gen_anchors.py: --floor YYYY-MM-DD is required (no current header)")
        floor = m.group(1)
    fl = datetime.datetime.strptime(floor, "%Y-%m-%d").replace(tzinfo=datetime.timezone.utc)
    text = render(fl)
    if a.check:
        if not OUT.is_file() or OUT.read_text() != text:
            print(f"{OUT.relative_to(ROOT)} differs from keys/tls/*.crt — run: python3 tools/gen_anchors.py --floor {floor}")
            return 1
        print(f"{OUT.relative_to(ROOT)}: {text.count('BR_X509_TA_CA')} anchors, floor {floor} — up to date")
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {text.count('BR_X509_TA_CA')} anchors, floor {floor}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
